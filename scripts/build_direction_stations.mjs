// Which Stations does each Line serve in each direction, from the GTFS Feed?
//
// The coastal section is one-way (ADR-0007): a tram bound for the coast calls
// at Platja Malva-rosa and Platja les Arenes and never at Cabanyal; coming back
// it calls at Dr. Lluch and Cabanyal and never at the beach. The feed says so
// in its trips, so this reads it there rather than listing Stations by name.
//
// A trip's direction is its travel along the Line's polyline: the sign of the
// summed track-distance steps between consecutive Stops that lie on the
// polyline. Dozens of trunk Stations outvote the few coastal ones the polyline
// projects badly, so Cabanyal's bogus position cannot flip a trip.
//
// Writes src/data/direction_stations.json: GTFS stop ids per Line per
// direction. The engine reads it only for Lines that have a return track.
//
// Usage: npx vite-node scripts/build_direction_stations.mjs [gtfsDir]

import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';
import engine from '../src/services/trainPositionEngine.js';

const projectRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const newestFeed = () => {
  const dated = fs.readdirSync(projectRoot)
    .filter(name => /^\d{8}_\d{6}_/.test(name))
    .filter(name => fs.existsSync(path.join(projectRoot, name, 'stops.txt')))
    .sort()
    .reverse();
  if (!dated.length) throw new Error('No GTFS feed directory found in the project root');
  return path.join(projectRoot, dated[0]);
};
const gtfsDir = process.argv[2] || newestFeed();
const outPath = path.join(projectRoot, 'src', 'data', 'direction_stations.json');

const readCsv = (name) => {
  const lines = fs.readFileSync(path.join(gtfsDir, name), 'utf8').trim().split('\n');
  const headers = lines[0].trim().split(',');
  return lines.slice(1).map((line) => {
    const parts = line.trim().split(',');
    const row = {};
    headers.forEach((h, i) => { row[h] = parts[i]; });
    return row;
  });
};

const stopNames = new Map(readCsv('stops.txt').map(s => [s.stop_id, s.stop_name]));
const tripLine = new Map(readCsv('trips.txt').map(t => [t.trip_id, t.route_id.split('-')[0].replace(/^V/, '')]));

const stopsByTrip = new Map();
for (const row of readCsv('stop_times.txt')) {
  if (!tripLine.has(row.trip_id)) continue;
  if (!stopsByTrip.has(row.trip_id)) stopsByTrip.set(row.trip_id, []);
  stopsByTrip.get(row.trip_id).push({ stopId: row.stop_id, seq: Number(row.stop_sequence) });
}

const sets = {};
for (const [tripId, stops] of stopsByTrip) {
  const lineId = tripLine.get(tripId);
  // Track distance of the Stations the polyline actually reaches.
  const onTrack = new Map(engine.getLineStations(lineId).map(s => [s.stopId, s.trackDist]));
  stops.sort((a, b) => a.seq - b.seq);
  const dists = stops.map(s => onTrack.get(s.stopId)).filter(d => d !== undefined);
  let travel = 0;
  for (let i = 1; i < dists.length; i++) travel += Math.sign(dists[i] - dists[i - 1]);
  if (travel === 0) continue;

  const key = travel > 0 ? 'forward' : 'reverse';
  sets[lineId] ??= { forward: new Set(), reverse: new Set() };
  for (const s of stops) sets[lineId][key].add(s.stopId);
}

const out = { _comment: 'Generated by scripts/build_direction_stations.mjs from the GTFS Feed. Do not edit.', lines: {} };
for (const lineId of Object.keys(sets).sort((a, b) => Number(a) - Number(b))) {
  const { forward, reverse } = sets[lineId];
  const sort = (set) => [...set].sort((a, b) => Number(a) - Number(b));
  out.lines[lineId] = { forward: sort(forward), reverse: sort(reverse) };
  const only = (a, b) => sort(a).filter(id => !b.has(id)).map(id => stopNames.get(id));
  console.log(`L${lineId}: forward only [${only(forward, reverse).join(', ')}]  reverse only [${only(reverse, forward).join(', ')}]`);
}

fs.writeFileSync(outPath, JSON.stringify(out) + '\n');
console.log('Wrote', path.relative(projectRoot, outPath), 'from', path.basename(gtfsDir));
